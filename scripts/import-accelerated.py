#!/usr/bin/env python3
"""Generate Accelerated's offline library from the pinned, vendored CC-BY HTML.

Run with --check to verify source hashes and reproducible output without writes.
Uses the same text-preserving HTML reader as Core; never downloads at runtime.
"""
import argparse
import hashlib
import importlib.util
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
TARGET = ROOT / 'src/content'
spec = importlib.util.spec_from_file_location('core_import', ROOT / 'scripts/import-srd.py')
core = importlib.util.module_from_spec(spec)
spec.loader.exec_module(core)

# Match the existing Rules library's topic names; preserve book chapters as tags.
CHAPTER_CATEGORIES = {
    'Fate Accelerated Edition': 'About',
    'Get Started!': 'Basics',
    'Telling Stories Together': 'Basics',
    'Who Do You Want To Be?': 'Characters',
    'HowTo Do Stuff: Outcomes, Actions, and Approaches': 'Actions & outcomes',
    'Challenges, Contests, and Conflicts': 'Challenges & conflicts',
    'Ouch! Damage, Stress, and Consequences': 'Challenges & conflicts',
    'Aspects and Fate Points': 'Aspects & Fate points',
    'Stunts': 'Skills & stunts',
    'Getting Better at Doing Stuff: Character Advancement': 'Campaigns & advancement',
    'Being the GM': 'Running the game',
    'Example Characters': 'Characters',
}


def outputs():
    lock = json.loads((TARGET / 'source-lock.json').read_text())
    source = lock['acceleratedSource']
    raw = (TARGET / 'source/fate-accelerated-SRD.html').read_bytes()
    digest = hashlib.sha256(raw).hexdigest()
    blob = hashlib.sha1(b'blob ' + str(len(raw)).encode() + b'\0' + raw).hexdigest()
    if (digest, blob, len(raw)) != (source['sha256'], source['blobSha'], source['bytes']):
        raise ValueError('Accelerated source differs from the pinned GitHub blob.')
    parser = core.Reader()
    parser.chapter = parser.title = 'Fate Accelerated Edition'
    parser.feed(raw.decode('utf-8-sig'))
    parser.close()
    parser.flush()
    if core.ATTRIBUTION not in '\n'.join(s['body'] for s in parser.sections):
        raise ValueError('Accelerated CC-BY attribution is missing.')
    source_url = f"{lock['repositoryUrl']}/blob/{lock['revision']}/{source['path']}"
    version = f"accelerated-srd-github-{lock['revision'][:12]}-cc"
    transformation = ('The original pinned CC-BY HTML is converted into heading-based offline entries and '
                      'Markdown using the Core HTML reader. Visible link text and examples are retained; '
                      'whitespace and tables are normalized; artwork, styling and empty placeholders are omitted. '
                      'The upstream Markdown conversion, which omits some linked text, is not used.')
    reading_links = json.loads((TARGET / 'accelerated-reading-links.json').read_text())
    if reading_links['sourceRevision'] != lock['revision']:
        raise ValueError('Review Accelerated reading-page mappings for the new pinned source revision.')
    destinations = {section['sourceLine']: section['path'] for section in reading_links['sections']}
    entries = []
    markdown = ['<!-- Generated by scripts/import-accelerated.py; original notices retained. -->',
                f'<!-- Source: {source_url} -->', '']
    for section in parser.sections:
        markdown += ['#' * section['level'] + ' ' + section['title'], '', core.markdown_body(section['body']), '']
        if not section['body']:
            continue
        if section['line'] not in destinations or section['chapter'] not in CHAPTER_CATEGORIES:
            raise ValueError(f"Review category and reading destination for {section['title']}")
        slug = re.sub(r'[^a-z0-9]+', '-', section['title'].lower()).strip('-')
        entries.append(dict(id=f'accelerated-{len(entries)+1:03d}-{slug}', title=section['title'],
                            category=CHAPTER_CATEGORIES[section['chapter']], body=section['body'],
                            source='Fate Accelerated SRD · GitHub · CC BY 3.0',
                            sourceUrl=f"{source_url}#L{section['line']}",
                            readingUrl=reading_links['baseUrl'] + destinations[section['line']], sourceSection=section['title'],
                            sourceLine=section['line'], contentVersion=version,
                            tags=[section['chapter'], 'Fate Accelerated']))
    md = ('\n'.join(markdown).rstrip() + '\n').encode()
    metadata = dict(title='Fate Accelerated Edition SRD', version=version, converterVersion=2,
                    repository=lock['repository'], repositoryUrl=lock['repositoryUrl'], revision=lock['revision'],
                    sourceUrl=source_url, sourcePath=source['path'], readingUrl='https://fate-srd.com/fate-accelerated',
                    readingLinksVerifiedAt=reading_links['verifiedAt'],
                    sourceBlobSha=blob, sourceSha256=digest, sourceBytes=len(raw),
                    sourceFormat='HTML (original CC-BY SRD in the GitHub repository)',
                    markdownPath='src/content/source/fate-accelerated.generated.md',
                    markdownSha256=hashlib.sha256(md).hexdigest(), copyright='©2013 Evil Hat Productions, LLC.',
                    license='Creative Commons Attribution 3.0 Unported', licenseUrl='https://creativecommons.org/licenses/by/3.0/',
                    attribution=core.ATTRIBUTION, transformation=transformation, entryCount=len(entries))
    return {TARGET / 'accelerated-reference.json': core.json_bytes(entries),
            TARGET / 'accelerated-metadata.json': core.json_bytes(metadata),
            TARGET / 'source/fate-accelerated.generated.md': md}

if __name__ == '__main__':
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--check', action='store_true')
    args = cli.parse_args()
    try:
        for path, data in outputs().items():
            if args.check:
                if not path.exists() or path.read_bytes() != data:
                    raise ValueError(f'Generated content is out of date: {path.relative_to(ROOT)}')
            else:
                path.write_bytes(data)
        print('Verified Accelerated source and offline references.' if args.check else 'Generated Accelerated references.')
    except (OSError, ValueError) as error:
        cli.exit(1, str(error) + '\n')
